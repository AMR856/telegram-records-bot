import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import JSON, BigInteger, DateTime, ForeignKey, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, utcnow


# Define an enumeration for the different statuses that a listener can have, including stopped, running, and error
class ListenerStatus(StrEnum):
    STOPPED = "stopped"
    RUNNING = "running"
    ERROR = "error"


class BotListener(Base):
    __tablename__ = "listeners"

    # Unique identifier for the listener. Automatically generates a UUID4 upon creation.
    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    
    # Foreign key linking this listener to the user who created it. Cascades deletion if the user is removed.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )

    # An optional, user-defined name or label to easily identify this listener in a UI.
    label: Mapped[str | None] = mapped_column(String(100))

    # The raw channel identifier provided by the user (e.g., an @username, URL, or raw ID).
    channel_input: Mapped[str] = mapped_column(String(255))
    
    # The actual numerical chat ID resolved by the platform API from the channel_input.
    resolved_chat_id: Mapped[int | None] = mapped_column(BigInteger)
    
    # The human-readable title of the chat or channel being listened to.
    chat_title: Mapped[str | None] = mapped_column(String(255))
    
    # The username of the bot that is listening to the channel.
    bot_username: Mapped[str | None] = mapped_column(String(64))
    
    # The securely encrypted API token for the bot.
    token_encrypted: Mapped[str] = mapped_column(Text)
    
    # A hashed version of the token used to ensure the same token isn't registered multiple times.
    token_fingerprint: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    
    # A safely masked version of the bot token (e.g., "12345***:***ABCDE") for UI display purposes.
    token_hint: Mapped[str] = mapped_column(String(64))
    
    # The current operational state of the listener (e.g., 'running', 'stopped', 'error'). Defaults to STOPPED.
    status: Mapped[str] = mapped_column(String(16), default=ListenerStatus.STOPPED)
    
    # Stores the error message or traceback if the listener encounters a critical failure.
    last_error: Mapped[str | None] = mapped_column(Text)
    
    # The timezone-aware timestamp marking exactly when the last error occurred.
    last_error_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    
    # The ID of the last successfully processed update (e.g., Telegram update_id), used to prevent duplicate processing.
    last_update_id: Mapped[int | None] = mapped_column(BigInteger)
    
    # A JSON payload used to persist dynamic state or configuration for the listener's internal parser.
    parser_state: Mapped[dict] = mapped_column(JSON, default=dict)
    
    # The timezone-aware timestamp of when the listener was initially created.
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    
    # The timezone-aware timestamp of when the listener was last modified, updated automatically on change.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )

    # SQLAlchemy ORM relationship back to the parent User who owns this listener.
    user: Mapped["User"] = relationship(back_populates="listeners")  # noqa: F821
    
    # Relationship to any payments associated with this listener. Deletes payments if the listener is removed.
    payments: Mapped[list["Payment"]] = relationship(  # noqa: F821
        back_populates="listener", cascade="all, delete-orphan"
    )
    
    # Relationship to all logs generated by this listener. Deletes logs if the listener is removed.
    logs: Mapped[list["ListenerLog"]] = relationship(  # noqa: F821
        back_populates="listener", cascade="all, delete-orphan"
    )